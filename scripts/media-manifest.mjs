import { execFileSync } from "node:child_process"
import { createHash } from "node:crypto"
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { fileURLToPath } from "node:url"
import { CATALOGUE } from "../packages/db/src/seed/catalogue.ts"

const requireFromWeb = createRequire(new URL("../apps/web/package.json", import.meta.url))
const sharp = requireFromWeb("sharp")
const publicDir = new URL("../apps/web/public/", import.meta.url)
const target = fileURLToPath(new URL("../packages/db/src/seed/bundled-media.ts", import.meta.url))

const slug = (s) =>
  s
    .toLowerCase()
    .replace(/œ/g, "oe")
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")

const byRef = new Map(CATALOGUE.map((p) => [p.ref, p]))

const keys = [
  ...readdirSync(new URL("catalogue/", publicDir))
    .filter((f) => f.endsWith(".webp"))
    .map((f) => `/catalogue/${f}`),
  "/logo.webp",
  "/texture.webp",
]

const entries = []
for (const key of keys) {
  const bytes = readFileSync(new URL(key.slice(1), publicDir))
  const { width, height } = await sharp(bytes).metadata()
  const name = key.split("/").pop()
  const product = /^(\d{4})-(\d+)\.webp$/.exec(name)
  const ref = product ? byRef.get(product[1]) : undefined
  let filename = name
  let tags = ["atelier"]
  if (product && ref) {
    filename = `${slug(ref.title)}-${product[1]}-${product[2]}.webp`
    tags = [ref.category]
  } else if (name === "lampes-collage.webp") tags = ["lampe-votive"]
  else if (name === "logo.webp" || name === "texture.webp") tags = ["marque"]
  entries.push({
    key,
    filename,
    bytes: bytes.length,
    width,
    height,
    hash: createHash("sha256").update(bytes).digest("hex"),
    tags,
  })
}
entries.sort((a, b) => (a.key < b.key ? -1 : 1))

writeFileSync(
  target,
  `// Generated by scripts/media-manifest.mjs (pnpm media:manifest). Do not edit.
export interface BundledMedia {
  key: string
  filename: string
  bytes: number
  width: number
  height: number
  hash: string
  tags: string[]
}

export const BUNDLED_MEDIA: BundledMedia[] = ${JSON.stringify(entries)}
`,
)
execFileSync("pnpm", ["exec", "biome", "format", "--write", target], { stdio: "ignore" })
console.info(`${entries.length} bundled images`)
