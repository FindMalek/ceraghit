export const invoiceSellerSchema = z.object({
  displayName: z.string().nullable(),
  legalName: z.string().nullable(),
  legalForm: z.string().nullable(),
  taxId: z.string().nullable(),
  registryNumber: z.string().nullable(),
  address: z.string().nullable(),
  postalCode: z.string().nullable(),
  city: z.string().nullable(),
  country: z.string(),
  phone: z.string().nullable(),
  email: z.string().nullable(),
  invoiceNote: localizedSchema.nullable(),
  bank: bankDetailsSchema.nullable(),
  /** Optional: invoices issued before the US account existed have no such key in their snapshot. */
  bankUsd: usdBankDetailsSchema.nullable().optional(),
})
export type InvoiceSellerView = z.infer<typeof invoiceSellerSchema>

export const invoiceViewSchema = z.object({
  orderId: z.string(),
  locale: invoiceLocaleSchema,
  orderLocale: invoiceLocaleSchema,
  /** Null until the invoice is issued: the page then shows a pro forma. */
  number: z.string().nullable(),
  issuedAt: z.string().nullable(),
  canIssue: z.boolean(),
  orderNumber: z.string(),
  orderStatus: orderStatusSchema,
  orderDate: z.string(),
  paidAt: z.string().nullable(),
  currency: currencySchema,
  paymentMethod: paymentMethodSchema,
  /** What the owner typed when he confirmed a transfer or Payoneer payment. */
  paymentReference: z.string().nullable(),
  items: z.array(orderItemSchema),
  subtotalMinor: z.number().int(),
  shippingMinor: z.number().int(),
  totalMinor: z.number().int(),
  customer: z.object({
    name: z.string(),
    email: z.string(),
    phone: z.string(),
    address: z.string(),
    postalCode: z.string().nullable(),
    city: z.string(),
    country: z.string(),
  }),
  seller: invoiceSellerSchema,
})
export type InvoiceView = z.infer<typeof invoiceViewSchema>

/** What a customer gets: no internal id, nothing to issue. */
export const publicInvoiceViewSchema = invoiceViewSchema.omit({ orderId: true, canIssue: true })
export type PublicInvoiceView = z.infer<typeof publicInvoiceViewSchema>
